#!/usr/bin/env node
/**
 * Generates _redirects (Netlify) so every URL from the old Joomla site at
 * www.custombullbars.com.au lands on the right page here. Old albums were
 * one per model, old photo pages were one per bull bar, and the photo file
 * names (32-char hashes) survived the migration, so photo links open the
 * exact bull bar in the finder pop-out via ?p=<hash>.
 *   node scripts/build-redirects.js   (writes _redirects in the repo root)
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');

// old brand folder -> new make key
const BRANDS = {
  'accessories-2': 'bus-and-coach', 'accessories': 'accessories', 'daf': 'daf', 'freightliner': 'freightliner',
  'fuso': 'fuso', 'hino': 'hino', 'isuzu': 'isuzu', 'isuzubullbars': 'isuzu', 'kenworth-bullbars': 'kenworth',
  'kenworth-bullbarsbullbars': 'kenworth', 'man': 'man', 'mack-bull-bars': 'mack', 'mercedes': 'mercedes',
  'scania-truck-bullbars': 'scania', 'volvo-bull-bars': 'volvo', 'western-star-bull-bars': 'western-star', 'ud': 'ud',
};
// old album tag (per brand folder) -> new model key. Keys are the tag exactly as it appeared in the old URL (decoded).
const ALBUMS = {
  'accessories-2': { 'bus': 'bus' },
  'accessories': { 'accessories': 'accessories' },
  'daf': { 'DAF': null }, // one album for the whole make -> make page
  'freightliner': { 'ARGOSY': 'argosy', 'BUMPER BAR FL': 'bumper-bar', 'CASCADIA': 'cascadia', 'COLUMBIA': 'columbia', 'CORONADO': 'coronado' },
  'fuso': { '918': '918', 'CANTER': 'canter', 'FIGHTER': 'fighter', 'FV': 'fv', 'SHOGUN': 'shogun' },
  'hino': { '300 SERIES': '300-series', '500 SERIES': '500-series', 'DUTRO': 'dutro', 'FE SERIES': 'fe-series', 'FG & FH SERIES': 'fg-and-fh-series', 'GH & FM SERIES': 'gh-and-fm-series' },
  'isuzu': { 'FRD': 'frd', 'isuzu': 'isuzu' },
  'kenworth-bullbars': { 'BUMPER-KW': 'bumper', 'C509': 'c509', 'K200': 'k200', 'K220': 'k220', 'T409': 't409', 'T604': 't604', 'T608': 't608', 'T609': 't609', 'T610 SAR': 't610-sar', 'T610': 't610', 'T659': 't659', 'T900': 't900', 'T904': 't904', 'T908': 't908', 'T909': 't909', 'T950': 't950', 'W Legend SAR': 'w-legend-sar' },
  'mack-bull-bars': { 'ANTHEM': 'anthem', 'BUMPER-MACK': 'bumper', 'GRANITE': 'granite', 'SUPERLINER': 'superliner', 'TITAN': 'titan', 'TRIDENT': 'trident' },
  'man': { 'TGL': 'tgl', 'TGM': 'tgm', 'TGS': 'tgs', 'TGX': 'tgx' },
  'mercedes': { '1844': '1844', '2633': '2633', '2648': '2648', '2658': '2658', 'ACTROS': 'actros', 'ATEGO': 'atego', 'BUMPER BAR-MB': 'bumper-bar', 'WALK PLATE': 'walk-plate' },
  'scania-truck-bullbars': { 'BUMPER-SCANIA': 'bumper', 'G series': 'g-series', 'R series': 'r-series', 'Walk Plates': 'walk-plates', 'XT series': 'xt-series' },
  'ud': { 'CONDOR': 'condor', 'CRONER': 'croner', 'GW': 'gw', 'MK11': 'mk11', 'PK17': 'pk17', 'PW': 'pw', 'QUON': 'quon' },
  'volvo-bull-bars': { 'FE': 'fe', 'FH': 'fh', 'FH16': 'fh16', 'FM': 'fm', 'SERIES 4': 'series-4', 'SERIES 5': 'series-5' },
  'western-star-bull-bars': { '4800': '4800', '4900': '4900', '5700': '5700', '6964': '6964', 'BUMPER W-STAR': 'bumper' },
};
// Kenworth and Isuzu albums were also reachable under the broken folder names
ALBUMS['kenworth-bullbarsbullbars'] = ALBUMS['kenworth-bullbars'];
ALBUMS['isuzubullbars'] = ALBUMS['isuzu'];

const models = new Set(fs.readdirSync(path.join(ROOT, 'content/models')).map(f => f.replace(/\.json$/, '')));
const enc = s => encodeURIComponent(s).replace(/%2F/g, '/');
const out = [];
out.push('# Generated by scripts/build-redirects.js - old www.custombullbars.com.au (Joomla) URLs -> this site.');
out.push('# Specific rules first; the per-brand catch-alls at the end stop anything from 404ing.');
out.push('');
out.push('# Pages');
out.push('/index.php                /          301');
out.push('/index.php/*              /:splat    301');
out.push('/about-us                 /about     301');
out.push('/about-us/*               /about     301');
out.push('/contact-us               /contact   301');
out.push('/contact-us/*             /contact   301');
out.push('/truck-bull-bars          /bull-bars 301');
out.push('');
let n = 0;
for (const [folder, make] of Object.entries(BRANDS)) {
  out.push(`# ${folder} -> ${make}`);
  for (const [tag, model] of Object.entries(ALBUMS[folder] || {})) {
    if (model && !models.has(`${make}--${model}`)) { console.warn(`no model ${make}--${model} for album ${folder}/${tag}`); continue; }
    const target = model ? `/bull-bars?make=${make}&model=${model}` : `/bull-bars?make=${make}`;
    out.push(`/truck-bull-bars/${folder}/view-album/tag-${enc(tag)}  ${target}  301`);
    out.push(`/truck-bull-bars/${folder}/view-album-image/tag-${enc(tag)}/:hash/:ext  ${target}&p=:hash  301`);
    n += 2;
  }
  out.push(`/truck-bull-bars/${folder}  /bull-bars?make=${make}  301`);
  out.push(`/truck-bull-bars/${folder}/*  /bull-bars?make=${make}  301`);
  out.push('');
  n += 2;
}
out.push('# Anything else under the old catalogue folder');
out.push('/truck-bull-bars/*  /bull-bars  301');
fs.writeFileSync(path.join(ROOT, '_redirects'), out.join('\n') + '\n');
console.log(`_redirects written: ${n + 8} rules`);
